import { createHash } from 'node:crypto';
import { strToU8, unzipSync, zipSync, type Zippable } from 'fflate';

/**
 * Evidence pack assembly and verification (Phase 28).
 *
 * A pack is a zip whose contents are fully described by `manifest.json`
 * (path, size and SHA-256 of every file) plus a standard `SHA256SUMS` file, so it
 * can be checked with plain tools:   shasum -a 256 -c SHA256SUMS
 *
 * Tamper evidence: the SHA-256 of `manifest.json` ("manifest hash") is recorded
 * in the database, in an append-only table, when the pack is issued. Anyone holding
 * a pack can recompute that hash and ask whether it was ever issued. Changing,
 * adding or removing any file changes the manifest or breaks a file hash.
 *
 * Output is DETERMINISTIC for the same inputs (fixed entry timestamps, sorted
 * paths), so a pack can be regenerated byte-for-byte for the same evidence.
 */

export const PACK_SCHEMA = 'ismartpay-loadtest-evidence-pack/1';
const MANIFEST = 'manifest.json';
const SUMS = 'SHA256SUMS';

export interface PackFile {
  path: string;
  data: string | Uint8Array;
}

export interface SourceRun {
  kind: string;
  id: string;
  finishedAt: string | null;
  environment: string;
  isReal: boolean;
}

export interface ManifestFile {
  path: string;
  bytes: number;
  sha256: string;
}

export interface PackManifest {
  schema: typeof PACK_SCHEMA;
  packId: string;
  generatedAt: string;
  generatedBy: string;
  toolVersion: string;
  libraryVersion: string;
  target: { id: string; name: string; host: string };
  /** What kind of evidence is inside: only `real` evidence counts toward “evidenced”. */
  basis: string;
  disclaimer: string;
  sourceRuns: SourceRun[];
  coverage: unknown;
  /** Every file except manifest.json and SHA256SUMS themselves. */
  files: ManifestFile[];
}

export interface AssembleInput {
  packId: string;
  generatedAt: Date;
  generatedBy: string;
  toolVersion: string;
  libraryVersion: string;
  target: PackManifest['target'];
  basis: string;
  disclaimer: string;
  sourceRuns: SourceRun[];
  coverage: unknown;
  files: PackFile[];
}

export interface AssembledPack {
  zip: Uint8Array;
  manifest: PackManifest;
  manifestSha256: string;
  zipSha256: string;
  fileCount: number;
}

export const sha256 = (data: string | Uint8Array): string =>
  createHash('sha256')
    .update(typeof data === 'string' ? Buffer.from(data, 'utf8') : data)
    .digest('hex');

const bytesOf = (d: string | Uint8Array): Uint8Array => (typeof d === 'string' ? strToU8(d) : d);

/** Reject paths that could escape the extraction directory ("zip slip") or collide. */
export function assertSafePath(path: string): void {
  if (
    !path ||
    path.startsWith('/') ||
    path.includes('\\') ||
    path.split('/').some((p) => p === '..' || p === '' || p === '.')
  ) {
    throw new Error(`Unsafe pack path: ${JSON.stringify(path)}`);
  }
}

export function readmeText(m: PackManifest): string {
  return `EVIDENCE PACK ${m.packId}
Target: ${m.target.name} (${m.target.host})
Generated: ${m.generatedAt} by ${m.generatedBy}
Control library: ${m.libraryVersion}   Evidence basis: ${m.basis}

READ THIS FIRST
${m.disclaimer}

WHAT IS INSIDE
  assessment/      the compliance matrix (HTML, XLSX, CSV, JSON), the control library and reviewer sign-offs
  reports/         the test reports the matrix is built from (JSON for machines, HTML for people)
  evidence/        the per-call evidence log (method, path, status, Request-Id, reference — never bodies or secrets)
  manifest.json    every file with its size and SHA-256, plus the source runs
  SHA256SUMS       the same hashes in the standard format

HOW TO CHECK THAT NOTHING WAS CHANGED
  1. Unzip, then run:   shasum -a 256 -c SHA256SUMS      (every line must say OK)
  2. Or:                npm run verify:evidence-pack -- <this-file>.zip
  3. Compute the manifest hash:   shasum -a 256 manifest.json
     and ask the issuer to confirm it was recorded when this pack was generated.
     The issuer keeps the hash in an append-only table; a pack that was edited after
     issue will not match any recorded hash.
`;
}

/** Builds the deterministic zip. Paths are sorted; entry times are fixed to generatedAt. */
export function assemblePack(input: AssembleInput): AssembledPack {
  const seen = new Set<string>();
  for (const f of input.files) {
    assertSafePath(f.path);
    if (f.path === MANIFEST || f.path === SUMS) throw new Error(`${f.path} is reserved`);
    if (seen.has(f.path)) throw new Error(`Duplicate pack path: ${f.path}`);
    seen.add(f.path);
  }

  const body = [...input.files].sort((a, b) => a.path.localeCompare(b.path));
  const manifestBase: Omit<PackManifest, 'files'> = {
    schema: PACK_SCHEMA,
    packId: input.packId,
    generatedAt: input.generatedAt.toISOString(),
    generatedBy: input.generatedBy,
    toolVersion: input.toolVersion,
    libraryVersion: input.libraryVersion,
    target: input.target,
    basis: input.basis,
    disclaimer: input.disclaimer,
    sourceRuns: input.sourceRuns,
    coverage: input.coverage,
  };
  // README is part of the manifest, so it is generated from the manifest header first.
  const readme = readmeText({ ...manifestBase, files: [] });
  const withReadme = [...body, { path: 'README.txt', data: readme }].sort((a, b) =>
    a.path.localeCompare(b.path),
  );

  const files: ManifestFile[] = withReadme.map((f) => {
    const b = bytesOf(f.data);
    return { path: f.path, bytes: b.length, sha256: sha256(b) };
  });
  const manifest: PackManifest = { ...manifestBase, files };
  const manifestBytes = strToU8(`${JSON.stringify(manifest, null, 2)}\n`);
  const manifestSha256 = sha256(manifestBytes);

  const sumLines = [
    ...files.map((f) => ({ path: f.path, sha: f.sha256 })),
    { path: MANIFEST, sha: manifestSha256 },
  ]
    .sort((a, b) => a.path.localeCompare(b.path))
    .map((l) => `${l.sha}  ${l.path}`)
    .join('\n');

  const mtime = input.generatedAt;
  const tree: Zippable = {};
  for (const f of withReadme) tree[f.path] = [bytesOf(f.data), { mtime }];
  tree[MANIFEST] = [manifestBytes, { mtime }];
  tree[SUMS] = [strToU8(`${sumLines}\n`), { mtime }];
  const zip = zipSync(tree, { level: 6 });

  return { zip, manifest, manifestSha256, zipSha256: sha256(zip), fileCount: files.length + 2 };
}

export interface VerifyResult {
  ok: boolean;
  manifestSha256: string | null;
  packId: string | null;
  fileCount: number;
  problems: string[];
  manifest: PackManifest | null;
}

/** Re-derives everything from the bytes: file hashes, sizes, the SHA256SUMS file and the manifest hash. */
export function verifyPack(zip: Uint8Array): VerifyResult {
  const problems: string[] = [];
  let entries: Record<string, Uint8Array>;
  try {
    entries = unzipSync(zip);
  } catch (e) {
    return {
      ok: false,
      manifestSha256: null,
      packId: null,
      fileCount: 0,
      problems: [`Not a readable zip: ${e instanceof Error ? e.message : String(e)}`],
      manifest: null,
    };
  }
  for (const p of Object.keys(entries)) {
    try {
      assertSafePath(p);
    } catch {
      problems.push(`Unsafe path in archive: ${JSON.stringify(p)}`);
    }
  }
  const mBytes = entries[MANIFEST];
  const sBytes = entries[SUMS];
  if (!mBytes) problems.push('manifest.json is missing');
  if (!sBytes) problems.push('SHA256SUMS is missing');
  if (!mBytes)
    return {
      ok: false,
      manifestSha256: null,
      packId: null,
      fileCount: Object.keys(entries).length,
      problems,
      manifest: null,
    };

  let manifest: PackManifest | null = null;
  try {
    manifest = JSON.parse(new TextDecoder().decode(mBytes)) as PackManifest;
  } catch {
    problems.push('manifest.json is not valid JSON');
  }
  const manifestSha256 = sha256(mBytes);
  if (!manifest || manifest.schema !== PACK_SCHEMA || !Array.isArray(manifest.files)) {
    problems.push('manifest.json does not match the expected schema');
    return {
      ok: false,
      manifestSha256,
      packId: null,
      fileCount: Object.keys(entries).length,
      problems,
      manifest: null,
    };
  }

  const listed = new Set<string>();
  for (const f of manifest.files) {
    listed.add(f.path);
    const data = entries[f.path];
    if (!data) {
      problems.push(`Listed file is missing: ${f.path}`);
      continue;
    }
    if (data.length !== f.bytes)
      problems.push(`Size changed: ${f.path} (${f.bytes} → ${data.length})`);
    if (sha256(data) !== f.sha256) problems.push(`Content changed: ${f.path}`);
  }
  for (const p of Object.keys(entries)) {
    if (p !== MANIFEST && p !== SUMS && !listed.has(p)) problems.push(`Unlisted file added: ${p}`);
  }

  if (sBytes) {
    const expected = new Map<string, string>(manifest.files.map((f) => [f.path, f.sha256]));
    expected.set(MANIFEST, manifestSha256);
    const got = new Map<string, string>();
    for (const line of new TextDecoder().decode(sBytes).split('\n').filter(Boolean)) {
      const m = /^([0-9a-f]{64}) {2}(.+)$/.exec(line);
      if (!m) problems.push(`Malformed SHA256SUMS line: ${line.slice(0, 80)}`);
      else got.set(m[2]!, m[1]!);
    }
    for (const [p, h] of expected)
      if (got.get(p) !== h) problems.push(`SHA256SUMS disagrees for ${p}`);
    for (const p of got.keys())
      if (!expected.has(p)) problems.push(`SHA256SUMS lists an unknown file: ${p}`);
  }

  return {
    ok: problems.length === 0,
    manifestSha256,
    packId: manifest.packId,
    fileCount: Object.keys(entries).length,
    problems,
    manifest,
  };
}
